def _rnd(d):
    """path 의 숫자를 소수 1자리로."""
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)


def _tf(d, fn):
    """path 의 모든 (x, y) 좌표쌍에 fn 적용."""
    def rep(m):
        x, y = fn(float(m.group(1)), float(m.group(2)))
        return f"{x:.1f} {y:.1f}"
    return _rnd(re.sub(r"(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)", rep, d))


def _wavy(cx, cy, R, A, n, phase=0.0, k=4):
    """반지름 R + A·cos(nθ) 의 매끄러운 물결 원(Catmull-Rom → 절대좌표 C)."""
    m = n * k
    pts = []
    for i in range(m):
        t = 2 * math.pi * i / m + phase
        r = R + A * math.cos(n * (t - phase))
        pts.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    f = lambda p: f"{p[0]:.1f} {p[1]:.1f}"
    out = [f"M{f(pts[0])}"]
    for i in range(m):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % m], pts[(i + 2) % m]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{f(c1)} {f(c2)} {f(p2)}")
    return _rnd("".join(out) + "Z")


